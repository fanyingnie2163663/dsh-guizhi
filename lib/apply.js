/**
 * Apply: preview, apply and rollback for the selected proposals (contract D7).
 *
 * Trust boundary (Review Focus #5): no write happens before a snapshot.
 * apply() validates the whole request first, so an illegal selection leaves no
 * trace; it then snapshots the state, backs up every pack file it is about to
 * overwrite (R-6B: rollback must restore an old pack, never delete it), writes
 * the ledger entries {path, existedBefore} into the snapshot's
 * packs-created.json and only then exports the packs (R-6A: a crash in the
 * export window is still recoverable). rollback() restores the backed-up bytes
 * of pre-existing packs, deletes exactly the packs this apply created (missing
 * ones are skipped) and then restores the state snapshot, so it can be repeated
 * safely. The packs it exports come from the store's 'packs' document written
 * by /pack (R-8A), never from a rebuild against the current map.
 *
 * Proposal kinds: 'install'/'skill' proposals never touch a profile and never
 * install anything, they only return a warning (D7). A non-empty 'pack'
 * proposal exports its stored pack file. home is passed in by the caller (D16);
 * this module reads no environment and never imports
 * '@deepseek-ai/dsh-tools' (D11).
 *
 * S2 skill install is OPT-IN and secondary: only the caller that passes
 * skillsHome (<$DSH_HOME>/skills) asks for it, and the HTTP route does that only
 * when body.installSkill === true. Without it the pack-only behavior, warnings
 * and output stay unchanged. When enabled, every non-empty pack is compiled by
 * lib/skillpack.js and installed as <skillsHome>/<stow-…>/SKILL.md:
 * - the skills root is canonicalized with realpath, so a dotfiles-style
 *   skillsHome that is itself a symlink works; a root that is unavailable,
 *   uncreatable or not writable never fails the apply — the skill part is
 *   skipped with a readable warning and the packs are still exported;
 * - a skill directory that is a symlink (possible escape) or a target that is
 *   not a regular file refuses the install before the snapshot; the same check
 *   runs again right before every write;
 * - a pre-existing SKILL.md is backed up into <snapshot>/skills-backup/<name>/
 *   before it is overwritten, entries go into skills-created.json, and rollback
 *   restores or deletes exactly them;
 * - a skill backup/write failure cleans up only the skill part, converges the
 *   skill ledger, pushes a warning and keeps the already exported packs.
 * Empty packs are skipped with a readable warning.
 *
 * preview() is pure: no disk, identical output for identical input. Its hash
 * is the lowercase sha256 of the canonical JSON of the item views (object keys
 * sorted at every depth) — a stable "exactly this will be applied" fingerprint.
 * Every failure is an ApplyError with a readable message and an optional .code
 * so the HTTP routes (Task 7) can map 400/404 without parsing text.
 *
 * @module @fanyingnie/dsh-guizhi/apply
 */
import { createHash } from 'node:crypto'
import { constants as fsConstants } from 'node:fs'
import { access, lstat, mkdir, readFile, realpath, rename, rm, rmdir, stat, writeFile } from 'node:fs/promises'
import { basename, dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { describeError } from './host.js'
import { exportPack, isPackEmpty, isSafePackId } from './packs.js'
import { schemas } from './schemas.js'
import { SKILL_FILE, buildPackSkill, isSkillPackName, skillNameForPack } from './skillpack.js'

/** Data-root sub-directories and the apply ledger file (contract D7). */
const PACKS_DIR = 'packs'
const SNAPSHOTS_DIR = 'snapshots'
const LEDGER_FILE = 'packs-created.json'
/** Per-snapshot directory holding the pre-overwrite bytes (R-6B). */
const BACKUP_DIR = 'packs-backup'
/** Per-snapshot skill ledger + pre-overwrite skill bytes (S2). */
const SKILLS_LEDGER_FILE = 'skills-created.json'
const SKILLS_BACKUP_DIR = 'skills-backup'
/** Per-snapshot metadata file; its presence distinguishes "missing" from "broken". */
const META_FILE = 'meta.json'

/** Snapshot tag of an apply; the id itself is generated by the store. */
const APPLY_TAG = 'before-apply'

/** Same snapshot-id boundary store.restore enforces, checked before path growth. */
const SNAPSHOT_ID = /^[0-9A-Za-z][0-9A-Za-z-]{0,63}$/

/** Single-file cap from the global constraints: 1 MB (exclusive). */
const MAX_JSON_BYTES = 1024 * 1024

/** Distinguishes the temp files of concurrent writers in this process. */
let tempSequence = 0

/** A failed preview/apply/rollback; .code is a stable token for the route layer (Task 7). */
export class ApplyError extends Error {
  /** @param {string} message @param {{ code?: string, cause?: unknown }} [options] */
  constructor(message, options) {
    super(message)
    this.name = 'ApplyError'
    const settings = isPlainObject(options) ? options : {}
    if (typeof settings.code === 'string' && settings.code !== '') this.code = settings.code
    if (settings.cause !== undefined) this.cause = settings.cause
  }
}

/** @param {unknown} value @returns {value is Record<string, unknown>} */
function isPlainObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

/**
 * Build an ApplyError with a stable code.
 * @param {string} message @param {string} code @param {unknown} [cause]
 */
function fail(message, code, cause) {
  return new ApplyError(message, cause === undefined ? { code } : { code, cause })
}

/**
 * Canonical JSON: object keys sorted at every depth, array order preserved.
 * preview.hash is defined on this string, not on JSON.stringify's key order.
 * @param {unknown} value @returns {string}
 */
function canonicalJson(value) {
  if (Array.isArray(value)) return '[' + value.map(canonicalJson).join(',') + ']'
  if (isPlainObject(value)) {
    const keys = Object.keys(value).sort()
    const body = keys.map((key) => JSON.stringify(key) + ':' + canonicalJson(value[key])).join(',')
    return '{' + body + '}'
  }
  return JSON.stringify(value)
}

/** Validate the data root the caller passed in (D16). @param {unknown} home @returns {string} */
function requireHome(home) {
  if (typeof home !== 'string' || home.trim() === '') {
    throw fail('apply/rollback 需要非空 home（数据根 $DSH_HOME/guizhi 由调用方传入）', 'INVALID_INPUT')
  }
  return resolve(home)
}

/** Validate the store methods this module calls. @param {unknown} store */
function requireStore(store) {
  const usable = store !== null && (typeof store === 'object' || typeof store === 'function')
  const missing = ['read', 'snapshot', 'restore'].filter((name) => !usable || typeof store[name] !== 'function')
  if (missing.length > 0) {
    throw fail('apply/rollback 需要 store（createStore 的实例），缺少：' + missing.join('/'), 'INVALID_INPUT')
  }
  return store
}

/**
 * Read one state document and turn a corrupt/unreadable file into an ApplyError.
 * @param {object} store @param {'map' | 'proposals'} name @param {string} corruptCode
 * @returns {Promise<unknown>} the parsed value, or null when the file is absent.
 */
async function readState(store, name, corruptCode) {
  let result
  try {
    result = await store.read(name)
  } catch (error) {
    throw fail('读取状态 "' + name + '" 失败：' + describeError(error), 'STATE_READ_FAILED', error)
  }
  if (result?.error !== null && result?.error !== undefined) {
    throw fail('状态 "' + name + '" 不可用：' + String(result.error), corruptCode)
  }
  return result?.value ?? null
}

/**
 * Resolve the selected proposals. ids undefined means "all proposals"; an
 * explicit list keeps its order and may not name an unknown id (a selection
 * that silently loses entries would apply less than the user was shown).
 * @param {unknown} proposals @param {unknown} ids @returns {object[]}
 */
function selectItems(proposals, ids) {
  if (proposals === null) throw fail('还没有提案数据，无法继续（请先扫描生成提案）', 'NO_PROPOSALS')
  const check = schemas.proposals.validate(proposals)
  if (!check.ok) throw fail('提案数据格式不符，无法继续：' + check.errors.join('；'), 'PROPOSALS_INVALID')
  const items = proposals.items
  // A duplicated proposal id would make preview list both entries while apply
  // resolves only the last one, so the document is rejected here instead.
  const knownIds = new Set()
  for (const item of items) {
    if (knownIds.has(item.id)) {
      throw fail('提案数据里存在重复的提案 id：' + JSON.stringify(item.id) + '（无法确定应用哪一条）', 'PROPOSALS_INVALID')
    }
    knownIds.add(item.id)
  }
  if (ids === undefined) return items.slice()
  if (!Array.isArray(ids)) throw fail('ids 必须是提案 id 数组', 'IDS_INVALID')
  const byId = new Map()
  for (const item of items) byId.set(item.id, item)
  const seen = new Set()
  const selected = []
  for (const [index, id] of ids.entries()) {
    if (typeof id !== 'string' || id === '') {
      throw fail('ids[' + index + '] 必须是非空字符串', 'IDS_INVALID')
    }
    if (seen.has(id)) throw fail('ids 里有重复的提案 id：' + JSON.stringify(id), 'IDS_INVALID')
    seen.add(id)
    const item = byId.get(id)
    if (item === undefined) {
      throw fail('未知的提案 id：' + JSON.stringify(id) + '（提案可能已更新，请重新预览）', 'UNKNOWN_PROPOSAL')
    }
    selected.push(item)
  }
  return selected
}

/**
 * Copy the four proposal fields preview shows, so internal fields can never
 * change the previewed fingerprint.
 * @param {object[]} items @returns {Array<{ id: string, kind: string, title: string, effect: string }>}
 */
function itemViews(items) {
  return items.map((item) => ({ id: item.id, kind: item.kind, title: item.title, effect: item.effect }))
}

/**
 * Preview exactly what apply(ids) would do. Pure: reads no disk, writes
 * nothing, and returns the same { items, hash } for the same input.
 *
 * @param {{ scan?: unknown, map?: unknown, proposals?: unknown, store?: unknown, ids?: unknown }} [input]
 *   scan/map/store belong to the shared call shape; v1's preview needs none of
 *   them, and passing them changes neither the result nor the disk.
 * @returns {Promise<{ items: Array<{ id: string, kind: string, title: string, effect: string }>, hash: string }>}
 * @throws {ApplyError} unknown/non-string/duplicate ids, or unusable proposals
 */
export async function preview(input) {
  const source = isPlainObject(input) ? input : {}
  const items = itemViews(selectItems(source.proposals ?? null, source.ids))
  const hash = createHash('sha256').update(canonicalJson(items), 'utf8').digest('hex')
  return { items, hash }
}

/** Attach the snapshot id to a post-snapshot failure so the caller can roll back. */
function withSnapshot(error, snapshotId) {
  error.snapshotId = snapshotId
  return error
}

/** Absolute path of the pre-overwrite backup for one pack target (R-6B). */
function backupFileFor(home, snapshotId, target) {
  return join(home, SNAPSHOTS_DIR, snapshotId, BACKUP_DIR, basename(target))
}

/** Read one file as bytes; undefined when it does not exist (any other error is real). */
async function readBytesIfExists(file) {
  try {
    return await readFile(file)
  } catch (error) {
    if (error?.code === 'ENOENT') return undefined
    throw error
  }
}

/** Write bytes atomically (private temp file beside the target, then rename). */
async function writeAtomic(file, data) {
  await mkdir(dirname(file), { recursive: true })
  tempSequence += 1
  const temp = file + '.' + process.pid + '.' + tempSequence + '.tmp'
  try {
    await writeFile(temp, data)
    await rename(temp, file)
  } catch (error) {
    await rm(temp, { force: true }).catch(() => {})
    throw error
  }
}

/**
 * Write the rollback ledger atomically (temp + rename), under the same 1 MB
 * single-file cap as the rest of the data root.
 * @param {string} file @param {unknown} value
 */
async function writeJsonAtomic(file, value) {
  let text
  try {
    text = JSON.stringify(value, null, 2)
  } catch (error) {
    throw new Error('无法序列化回滚记账：' + describeError(error))
  }
  text += '\n'
  const bytes = Buffer.byteLength(text, 'utf8')
  if (bytes >= MAX_JSON_BYTES) throw new Error('回滚记账超过单文件 1MB 上限：' + bytes + ' 字节')
  await writeAtomic(file, text)
}

/**
 * Normalize the optional skillsHome: absent means "keep the pack-only v1
 * behavior"; anything else must be a non-empty string and is resolved once.
 * @param {unknown} skillsHome
 * @returns {string | null}
 */
function optionalSkillsHome(skillsHome) {
  if (skillsHome === undefined) return null
  if (typeof skillsHome !== 'string' || skillsHome.trim() === '') {
    throw fail('skillsHome 必须是非空字符串（$DSH_HOME/skills 由调用方传入）', 'INVALID_INPUT')
  }
  return resolve(skillsHome)
}

/**
 * Whether target stays inside root. Both sides are resolved absolute paths; a
 * relative result of '' or starting with '..' escapes the root and is refused.
 * @param {string} root @param {string} target
 * @returns {boolean}
 */
function insideRoot(root, target) {
  const inside = relative(root, target)
  return inside !== '' && inside !== '..' && !inside.startsWith('..' + sep) && !isAbsolute(inside)
}

/** Absolute path of one installed skill file, refusing a non-kebab name. */
function skillTargetFor(skillsRoot, name) {
  if (!isSkillPackName(name)) {
    throw fail('技能名不是合法的 kebab-case 名：' + JSON.stringify(name), 'PACK_INVALID')
  }
  return join(skillsRoot, name, SKILL_FILE)
}

/** Absolute path of the pre-overwrite backup of one skill (S2, mirrors R-6B). */
function skillBackupFileFor(home, snapshotId, name) {
  return join(home, SNAPSHOTS_DIR, snapshotId, SKILLS_BACKUP_DIR, name, SKILL_FILE)
}

/** Best-effort removal of a directory that should now be empty. */
async function removeEmptyDir(dir) {
  try {
    await rmdir(dir)
  } catch {
    // ENOTEMPTY/ENOENT: another skill still uses the directory, or it is gone.
  }
}

/** Internal code: the skills root is unusable, so the opt-in install is skipped. */
const SKILLS_ROOT_UNAVAILABLE = 'SKILLS_ROOT_UNAVAILABLE'

/**
 * Resolve the skills root to its canonical (realpath) directory.
 *
 * A dotfiles-style skillsHome that is itself a symlink is allowed: stat()
 * follows the link to prove it is a directory and realpath() yields the one
 * canonical root every later containment check uses. A missing root is created
 * on demand when create is true (apply, opt-in install only); every failure
 * carries SKILLS_ROOT_UNAVAILABLE so apply can degrade to a warning instead of
 * failing the whole export. rollback calls it with create:false, so a broken
 * root only matters when the ledger actually carries entries.
 *
 * @param {string} skillsHome @param {{ create?: boolean }} [options]
 * @returns {Promise<string>} canonical skills root
 */
async function resolveSkillsRoot(skillsHome, options) {
  const create = options?.create === true
  let info
  try {
    info = await stat(skillsHome)
  } catch (error) {
    if (error?.code !== 'ENOENT') {
      throw fail('检查 skillsHome 失败：' + skillsHome + '：' + describeError(error), SKILLS_ROOT_UNAVAILABLE, error)
    }
    if (!create) return resolve(skillsHome)
    try {
      await mkdir(skillsHome, { recursive: true })
    } catch (mkdirError) {
      throw fail('技能根不可创建：' + skillsHome + '：' + describeError(mkdirError), SKILLS_ROOT_UNAVAILABLE, mkdirError)
    }
    try {
      info = await stat(skillsHome)
    } catch (statError) {
      throw fail('检查 skillsHome 失败：' + skillsHome + '：' + describeError(statError), SKILLS_ROOT_UNAVAILABLE, statError)
    }
  }
  if (!info.isDirectory()) throw fail('skillsHome 不是目录：' + skillsHome, SKILLS_ROOT_UNAVAILABLE)
  let canonical
  try {
    canonical = await realpath(skillsHome)
  } catch (error) {
    throw fail('解析 skillsHome 规范路径失败：' + skillsHome + '：' + describeError(error), SKILLS_ROOT_UNAVAILABLE, error)
  }
  if (create) {
    try {
      await access(canonical, fsConstants.W_OK)
    } catch (error) {
      throw fail('skillsHome 不可写：' + skillsHome + '：' + describeError(error), SKILLS_ROOT_UNAVAILABLE, error)
    }
  }
  return canonical
}

/**
 * Refuse a skill target that could escape the canonical root: the
 * <root>/<name> directory must not be a symlink, must be a real directory
 * inside the root after realpath, and that directory must be exactly
 * <root>/<name>; an existing SKILL.md must be a regular file (not a symlink).
 * Called once before the snapshot (a failure refuses the apply) and again right
 * before every write (a failure degrades the opt-in install to a warning).
 * @param {string} skillsRoot canonical skills root
 * @param {{ name: string, path: string }} skill
 */
async function assertSkillTargetSafe(skillsRoot, skill) {
  const dir = dirname(skill.path)
  let dirInfo
  try {
    dirInfo = await lstat(dir)
  } catch (error) {
    if (error?.code === 'ENOENT') return
    throw fail('检查技能目录失败：' + dir + '：' + describeError(error), 'SKILL_TARGET_UNSAFE', error)
  }
  if (dirInfo.isSymbolicLink()) {
    throw fail('技能目录是符号链接（可能逃逸 skillsHome），拒绝写入：' + dir, 'SKILL_TARGET_UNSAFE')
  }
  if (!dirInfo.isDirectory()) {
    throw fail('技能目标父路径不是目录，拒绝写入：' + dir, 'SKILL_TARGET_UNSAFE')
  }
  let canonicalDir
  try {
    canonicalDir = await realpath(dir)
  } catch (error) {
    throw fail('解析技能目录规范路径失败：' + dir + '：' + describeError(error), 'SKILL_TARGET_UNSAFE', error)
  }
  if (relative(skillsRoot, canonicalDir) !== skill.name) {
    throw fail('技能目录不在 skillsHome 规范根内：' + dir, 'SKILL_TARGET_UNSAFE')
  }
  let targetInfo
  try {
    targetInfo = await lstat(skill.path)
  } catch (error) {
    if (error?.code === 'ENOENT') return
    throw fail('检查技能安装目标失败：' + skill.path + '：' + describeError(error), 'SKILL_TARGET_UNSAFE', error)
  }
  if (!targetInfo.isFile() || targetInfo.isSymbolicLink()) {
    throw fail('技能安装目标已存在但不是普通文件，拒绝覆盖：' + skill.path, 'SKILL_TARGET_UNSAFE')
  }
}

/**
 * Resolve the skill install of every plan before the snapshot (S2): an empty
 * pack is skipped with a warning, a non-empty one gets a validated kebab name,
 * a target inside the canonical skillsRoot that is absent or a regular file,
 * and its compiled markdown. plan.skill is undefined for empty packs.
 * @param {{ plans: object[], skillsRoot: string, warnings: string[] }} input
 */
async function planSkillInstalls({ plans, skillsRoot, warnings }) {
  for (const plan of plans) {
    if (isPackEmpty(plan.pack)) {
      warnings.push('装配清单「' + String(plan.pack.title ?? plan.pack.id) + '」没有工具/技能，跳过技能安装')
      continue
    }
    let name
    try {
      name = skillNameForPack(plan.pack)
    } catch (error) {
      throw fail('装配清单无法安装为工作流技能：' + describeError(error), 'PACK_INVALID', error)
    }
    const path = skillTargetFor(skillsRoot, name)
    if (!insideRoot(skillsRoot, path)) {
      throw fail('技能安装目标不在 skillsHome 内，拒绝写入：' + path, 'SKILL_TARGET_UNSAFE')
    }
    let compiled
    try {
      compiled = buildPackSkill(plan.pack)
    } catch (error) {
      throw fail('装配清单无法编译成工作流技能：' + describeError(error), 'PACK_INVALID', error)
    }
    const skill = { name, path, markdown: compiled.markdown }
    // Refuses a symlinked/escaping skill directory before anything is written.
    await assertSkillTargetSafe(skillsRoot, skill)
    plan.skill = skill
  }
}

/**
 * Plan the ledger and back up every pack this apply is about to overwrite
 * (R-6B). Runs after the state snapshot and before the ledger/export, so a
 * crash in the export window always has both a ledger and a backup for every
 * file the apply may touch.
 * @param {{ home: string, snapshotId: string, plans: object[] }} input
 * @returns {Promise<Array<{ path: string, existedBefore: boolean }>>}
 */
async function prepareEntries({ home, snapshotId, plans }) {
  const entries = []
  const seen = new Set()
  for (const plan of plans) {
    // apply() already refuses an unsafe id before the snapshot; keeping the
    // check beside the path builder too means no future caller can join an
    // unsafe id into <home>/packs unnoticed.
    if (!isSafePackId(plan.pack.id)) {
      throw fail('存储的能力包 id 不是安全的文件名，拒绝导出：' + JSON.stringify(plan.pack.id), 'PACK_INVALID')
    }
    const target = join(home, PACKS_DIR, plan.pack.id + '.json')
    if (seen.has(target)) continue
    seen.add(target)
    let previous
    try {
      previous = await readBytesIfExists(target)
    } catch (error) {
      throw fail('检查目标能力包失败：' + target + '：' + describeError(error), 'PACK_BACKUP_FAILED', error)
    }
    if (previous === undefined) {
      entries.push({ path: target, existedBefore: false })
      continue
    }
    if (previous.length >= MAX_JSON_BYTES) {
      throw fail('已有能力包超过单文件 1MB 上限，无法先备份再覆盖：' + target, 'PACK_BACKUP_FAILED')
    }
    try {
      await writeAtomic(backupFileFor(home, snapshotId, target), previous)
    } catch (error) {
      throw fail('备份已有能力包失败（未覆盖任何文件）：' + target + '：' + describeError(error), 'PACK_BACKUP_FAILED', error)
    }
    entries.push({ path: target, existedBefore: true })
  }
  return entries
}

/**
 * Back up every pre-existing skill file this apply is about to overwrite and
 * build the skills-created.json entries {name, path, existedBefore} (S2, same
 * crash-recovery contract as prepareEntries).
 * @param {{ home: string, snapshotId: string, plans: object[] }} input
 * @returns {Promise<Array<{ name: string, path: string, existedBefore: boolean }>>}
 */
async function prepareSkillEntries({ home, snapshotId, plans }) {
  const entries = []
  for (const plan of plans) {
    if (plan.skill === undefined) continue
    const target = plan.skill.path
    let previous
    try {
      previous = await readBytesIfExists(target)
    } catch (error) {
      throw fail('读取既有技能文件失败（未覆盖任何技能）：' + target + '：' + describeError(error), 'SKILL_BACKUP_FAILED', error)
    }
    if (previous === undefined) {
      entries.push({ name: plan.skill.name, path: target, existedBefore: false })
      continue
    }
    try {
      await writeAtomic(skillBackupFileFor(home, snapshotId, plan.skill.name), previous)
    } catch (error) {
      throw fail('备份已有技能失败（未覆盖任何技能）：' + target + '：' + describeError(error), 'SKILL_BACKUP_FAILED', error)
    }
    entries.push({ name: plan.skill.name, path: target, existedBefore: true })
  }
  return entries
}

/**
 * Undo the skill writes of a failed apply: delete the skills this call created
 * and put overwritten skills back from their backup. Only entries actually
 * written are touched. Returns the entries whose cleanup did NOT finish, so the
 * ledger keeps exactly what a later rollback still has to fix.
 * @param {{ home: string, snapshotId: string, entries: object[], written: Set<string> }} input
 * @returns {Promise<object[]>}
 */
async function cleanupFailedSkillInstall({ home, snapshotId, entries, written }) {
  const remaining = []
  for (const entry of entries) {
    if (!written.has(entry.name)) continue
    try {
      if (entry.existedBefore) {
        const previous = await readBytesIfExists(skillBackupFileFor(home, snapshotId, entry.name))
        if (previous === undefined) throw new Error('备份缺失')
        await writeAtomic(entry.path, previous)
      } else {
        await rm(entry.path, { force: true })
        await removeEmptyDir(dirname(entry.path))
      }
    } catch {
      remaining.push(entry)
    }
  }
  return remaining
}

/**
 * Undo the file writes of a failed apply: delete files this call created and
 * put overwritten files back from their backup. Only entries whose path was
 * actually exported are touched. Returns the entries whose cleanup did NOT
 * finish, so the ledger keeps exactly what a later rollback still has to fix.
 * @param {{ home: string, snapshotId: string, entries: object[] }} input
 * @returns {Promise<object[]>}
 */
async function cleanupFailedExport({ home, snapshotId, entries }) {
  const remaining = []
  for (const entry of entries) {
    try {
      if (entry.existedBefore) {
        const previous = await readBytesIfExists(backupFileFor(home, snapshotId, entry.path))
        if (previous === undefined) throw new Error('备份缺失')
        await writeAtomic(entry.path, previous)
      } else {
        await rm(entry.path, { force: true })
      }
    } catch {
      remaining.push(entry)
    }
  }
  return remaining
}

/**
 * Replace the ledger with the entries a later rollback still has to handle;
 * remove it when nothing is left (a fully cleaned failed apply). Failures here
 * are swallowed on purpose — the export error is what the caller must see.
 * @param {string} file @param {object[]} entries
 */
async function settleLedger(file, entries) {
  try {
    if (entries.length === 0) await rm(file, { force: true })
    else await writeJsonAtomic(file, { entries })
  } catch {
    // Best effort: never mask the export failure.
  }
}

/**
 * Apply the selected proposals, in this order (Review Focus #5):
 * 1. read + validate proposals/ids, resolve every kind='pack' proposal to the
 *    pack /pack stored in the 'packs' document (R-8A: never rebuilt from the
 *    current map) and validate every stored pack id as a safe file name — an
 *    illegal request writes nothing, not even a snapshot;
 * 2. when the caller opted into the skill install (skillsHome passed), resolve
 *    the canonical skills root, compile every non-empty pack and validate its
 *    target BEFORE the snapshot; a root that is unavailable/uncreatable/
 *    unwritable only skips the skill part with a warning, because exporting the
 *    packs is the primary effect;
 * 3. store.snapshot('before-apply') — the state is safe before any change;
 * 4. back up every pre-existing pack file the apply will overwrite into
 *    <snapshot>/packs-backup/ and write the ledger entries {path,
 *    existedBefore} into the snapshot's packs-created.json before touching any
 *    pack file (R-6A + R-6B: a crash in the export window is recoverable and
 *    rollback can put an old pack back instead of deleting it);
 * 5. export each pack; a failed export deletes the files this call created,
 *    restores the overwritten ones from their backup, trims the ledger to
 *    whatever cleanup could not finish (removing it when nothing is left) and
 *    throws with the snapshot id so the caller can roll back;
 * 6. opt-in only: back up every pre-existing skill, write skills-created.json,
 *    then install each <skillsHome>/<stow-…>/SKILL.md. A failed skill backup or
 *    write cleans up only the skill part, converges the skill ledger, pushes a
 *    readable warning and still returns success — the exported packs stay.
 * kind 'install'/'skill' are never applied in v1: they only produce a warning.
 *
 * @param {{ ids?: unknown, store?: unknown, home?: unknown, skillsHome?: unknown, now?: unknown }} input
 *   skillsHome is opt-in (<$DSH_HOME>/skills): only the HTTP route decides it,
 *   and only when body.installSkill === true. Absent keeps the pack-only
 *   behavior. now is accepted for a stable call shape (Task 7 passes its clock);
 *   v1 does not read it, timestamps come from the store/pack writers.
 * @returns {Promise<{ applied: string[], warnings: string[], snapshotId: string, skills: Array<{ name: string, path: string }> }>}
 * @throws {ApplyError}
 */
export async function apply(input) {
  const source = isPlainObject(input) ? input : {}
  const store = requireStore(source.store)
  const home = requireHome(source.home)
  const requestedSkillsHome = optionalSkillsHome(source.skillsHome)
  const { ids } = source
  if (!Array.isArray(ids)) throw fail('apply 需要明确的 ids 数组（不默认应用全部提案）', 'IDS_INVALID')
  if (ids.length === 0) throw fail('没有选中任何提案（ids 为空），不执行应用', 'IDS_EMPTY')

  const proposals = await readState(store, 'proposals', 'PROPOSALS_INVALID')
  if (proposals === null) throw fail('还没有提案数据，无法应用（请先扫描生成提案）', 'NO_PROPOSALS')
  const selected = selectItems(proposals, ids)

  const warnings = []
  const plans = []
  /** store('packs') is read at most once, and only when a pack proposal is selected. */
  let packsDocument
  let packsLoaded = false
  async function loadPacksDocument() {
    if (packsLoaded) return packsDocument
    packsLoaded = true
    packsDocument = await readState(store, 'packs', 'PACKS_INVALID')
    if (packsDocument !== null) {
      const packsCheck = schemas.packs.validate(packsDocument)
      if (!packsCheck.ok) {
        throw fail('能力包存储格式不符：' + packsCheck.errors.join('；'), 'PACKS_INVALID')
      }
    }
    return packsDocument
  }
  for (const item of selected) {
    if (item.kind !== 'pack') {
      // install/skill 提案仍不安装（D7）；pack 应用时才会按 opt-in 安装派生工作流技能（S2）。
      warnings.push('v1 暂不安装：' + item.title + '（' + (item.kind === 'skill' ? '技能安装留待 v1.1' : 'profile 安装留待 v1.1') + '）')
      continue
    }
    // R-8A: export exactly the pack /pack stored for this proposal — never
    // rebuild from the current map, or preview and disk could disagree.
    const document = await loadPacksDocument()
    const stored = document === null ? undefined : document.packs.find((pack) => pack.id === item.id)
    if (stored === undefined) {
      throw fail(
        '没有找到提案 ' + JSON.stringify(item.id) + ' 对应的存储能力包（请重新点「生成装配清单」后再应用）',
        'PACK_NOT_FOUND',
      )
    }
    plans.push({ item, pack: stored })
  }

  // The pack id becomes a file name under <home>/packs, so its boundary is
  // validated HERE — before the snapshot, with the same rule exportPack uses.
  for (const plan of plans) {
    if (!isSafePackId(plan.pack.id)) {
      throw fail(
        '存储的能力包 id 不是安全的文件名，拒绝导出：' + JSON.stringify(plan.pack.id) + '（请重新生成装配清单）',
        'PACK_INVALID',
      )
    }
  }

  // S2: opt-in skill install. Planning happens before the snapshot so an unsafe
  // skill name/target refuses the whole apply; a broken skills root only skips
  // the skill part with a warning, because exporting the packs is the primary
  // effect.
  let skillsRoot = null
  if (requestedSkillsHome !== null) {
    const hasInstallableSkill = plans.some((plan) => !isPackEmpty(plan.pack))
    if (!hasInstallableSkill) {
      // No skill can be written (all packs empty); keep the readable skip note.
      await planSkillInstalls({ plans, skillsRoot: resolve(requestedSkillsHome), warnings })
    } else {
      try {
        skillsRoot = await resolveSkillsRoot(requestedSkillsHome, { create: true })
        await planSkillInstalls({ plans, skillsRoot, warnings })
      } catch (error) {
        if (error instanceof ApplyError && error.code === SKILLS_ROOT_UNAVAILABLE) {
          skillsRoot = null
          warnings.push('技能安装已跳过：' + error.message + '；装配清单已导出')
        } else {
          throw error
        }
      }
    }
  }

  // Snapshot before the first write (Review Focus #5).
  let snapshotId
  try {
    const snapshot = await store.snapshot(APPLY_TAG)
    snapshotId = snapshot?.id
  } catch (error) {
    throw fail('创建快照失败，未做任何改动：' + describeError(error), 'SNAPSHOT_FAILED', error)
  }
  // The id becomes a path segment below, so apply enforces the same boundary
  // rollback does instead of trusting the store blindly.
  if (typeof snapshotId !== 'string' || !SNAPSHOT_ID.test(snapshotId)) {
    throw fail('store.snapshot 返回了非法的快照 id，未写任何能力包：' + JSON.stringify(snapshotId), 'SNAPSHOT_INVALID')
  }

  // R-6A/R-6B: before touching any pack target, record every planned path AND
  // back up every pre-existing pack file, so a crash in the export window is
  // recoverable.
  const ledgerFile = join(home, SNAPSHOTS_DIR, snapshotId, LEDGER_FILE)
  const skillsLedgerFile = join(home, SNAPSHOTS_DIR, snapshotId, SKILLS_LEDGER_FILE)
  let entries
  try {
    entries = await prepareEntries({ home, snapshotId, plans })
  } catch (error) {
    throw withSnapshot(error, snapshotId)
  }
  try {
    await writeJsonAtomic(ledgerFile, { entries })
  } catch (error) {
    throw withSnapshot(
      fail('回滚记账写入失败，未写任何能力包：' + describeError(error), 'LEDGER_WRITE_FAILED', error),
      snapshotId,
    )
  }

  // Pack export first: it is the primary effect, so a later skill failure must
  // never force its cleanup.
  const applied = []
  const exported = new Set()
  try {
    for (const plan of plans) {
      const { path } = await exportPack({ home, pack: plan.pack })
      applied.push(plan.item.id)
      exported.add(path)
    }
  } catch (error) {
    const written = entries.filter((entry) => exported.has(entry.path))
    const remaining = await cleanupFailedExport({ home, snapshotId, entries: written })
    await settleLedger(ledgerFile, remaining)
    throw withSnapshot(
      fail('写能力包失败（已清理本次写出的文件，台账已按结果更新）：' + describeError(error), 'APPLY_WRITE_FAILED', error),
      snapshotId,
    )
  }

  // Opt-in skill install, isolated so a failure never undoes the packs.
  const skills = []
  if (skillsRoot !== null) {
    const writtenSkills = new Set()
    let skillEntries = []
    try {
      skillEntries = await prepareSkillEntries({ home, snapshotId, plans })
      if (skillEntries.length > 0) await writeJsonAtomic(skillsLedgerFile, { entries: skillEntries })
      for (const plan of plans) {
        if (plan.skill === undefined) continue
        // Re-check right before the write: a directory swapped after planning
        // must not be followed, and a hostile symlink is refused here.
        await assertSkillTargetSafe(skillsRoot, plan.skill)
        await writeAtomic(plan.skill.path, plan.skill.markdown)
        writtenSkills.add(plan.skill.name)
        skills.push({ name: plan.skill.name, path: plan.skill.path })
      }
    } catch (error) {
      // Skill installation is opt-in and secondary: undo only the skill part,
      // keep the exported packs and report a readable warning.
      const remainingSkills = await cleanupFailedSkillInstall({
        home,
        snapshotId,
        entries: skillEntries,
        written: writtenSkills,
      })
      await settleLedger(skillsLedgerFile, remainingSkills)
      skills.length = 0
      warnings.push('技能安装失败：' + describeError(error) + '；装配清单已导出')
    }
  }
  return { applied, warnings, snapshotId, skills }
}

/**
 * Read and validate the created-pack ledger of one snapshot. Missing ledger
 * means nothing to do for pack files (manual snapshot, or apply failed before
 * writing); a corrupt ledger refuses the rollback instead of silently leaving
 * packs behind. Every recorded path must stay inside <home>/packs: the ledger
 * is a file on disk, so its content is data, never a delete permission.
 *
 * Ledger shape (F1): { entries: [{ path, existedBefore }] }. A legacy
 * { paths: string[] } document is read as existedBefore:false so a snapshot
 * created before the upgrade can still be rolled back.
 * @param {string} snapshotDir @param {string} home
 * @returns {Promise<Array<{ path: string, existedBefore: boolean }>>} entries
 *   confined to <home>/packs
 */
async function readLedger(snapshotDir, home) {
  const file = join(snapshotDir, LEDGER_FILE)
  let raw
  try {
    raw = await readFile(file, 'utf8')
  } catch (error) {
    if (error?.code === 'ENOENT') return []
    throw fail('读取回滚记账失败：' + describeError(error), 'LEDGER_READ_FAILED', error)
  }
  let doc
  try {
    doc = JSON.parse(raw)
  } catch (error) {
    throw fail('快照的回滚记账已损坏，无法安全回滚：' + describeError(error), 'LEDGER_CORRUPT', error)
  }
  if (!isPlainObject(doc)) throw fail('快照的回滚记账已损坏：不是对象', 'LEDGER_CORRUPT')
  let rawEntries
  if (Array.isArray(doc.entries)) {
    rawEntries = doc.entries
  } else if (Array.isArray(doc.paths)) {
    rawEntries = doc.paths.map((path) => ({ path, existedBefore: false }))
  } else {
    throw fail('快照的回滚记账已损坏：缺少 entries 数组', 'LEDGER_CORRUPT')
  }
  const packsRoot = join(home, PACKS_DIR)
  const flags = new Map()
  const entries = []
  for (const [index, value] of rawEntries.entries()) {
    if (
      !isPlainObject(value) ||
      typeof value.path !== 'string' ||
      value.path === '' ||
      typeof value.existedBefore !== 'boolean'
    ) {
      throw fail('快照的回滚记账已损坏：entries[' + index + '] 必须是 {path, existedBefore}', 'LEDGER_CORRUPT')
    }
    const target = resolve(value.path)
    const inside = relative(packsRoot, target)
    if (inside === '' || inside === '..' || inside.startsWith('..' + sep) || isAbsolute(inside)) {
      throw fail('回滚记账里的路径不在 packs 目录内，拒绝删除：' + JSON.stringify(value.path), 'LEDGER_UNSAFE_PATH')
    }
    if (flags.has(target)) {
      if (flags.get(target) !== value.existedBefore) {
        throw fail('快照的回滚记账前后矛盾：' + JSON.stringify(value.path), 'LEDGER_CORRUPT')
      }
      continue
    }
    flags.set(target, value.existedBefore)
    entries.push({ path: target, existedBefore: value.existedBefore })
  }
  return entries
}

/**
 * Read and validate the optional skill ledger of one snapshot (S2).
 *
 * Missing ledger means this snapshot predates S2 or installed no skill (compat:
 * skip). An empty { entries: [] } ledger needs no skillsHome either, so an old
 * snapshot can never fail because $DSH_HOME/skills is missing/unusable. Only a
 * ledger that really carries entries requires a usable skillsHome; the root is
 * then canonicalized (a symlinked skillsHome is allowed) and every recorded
 * path must resolve inside it — the ledger is a file on disk, so its content is
 * data, never a delete permission. Every entry name must be a 'stow-' kebab
 * name, so a tampered ledger can never delete an unrelated user skill.
 *
 * Ledger shape: { entries: [{ name, path, existedBefore }] }.
 * @param {string} snapshotDir @param {string | null} skillsHome
 * @returns {Promise<{ entries: Array<{ name: string, path: string, existedBefore: boolean }>, root: string | null }>}
 */
async function readSkillsLedger(snapshotDir, skillsHome) {
  const file = join(snapshotDir, SKILLS_LEDGER_FILE)
  let raw
  try {
    raw = await readFile(file, 'utf8')
  } catch (error) {
    if (error?.code === 'ENOENT') return { entries: [], root: null }
    throw fail('读取技能回滚记账失败：' + describeError(error), 'LEDGER_READ_FAILED', error)
  }
  let doc
  try {
    doc = JSON.parse(raw)
  } catch (error) {
    throw fail('快照的技能回滚记账已损坏，无法安全回滚：' + describeError(error), 'LEDGER_CORRUPT', error)
  }
  if (!isPlainObject(doc)) throw fail('快照的技能回滚记账已损坏：不是对象', 'LEDGER_CORRUPT')
  if (!Array.isArray(doc.entries)) throw fail('快照的技能回滚记账已损坏：缺少 entries 数组', 'LEDGER_CORRUPT')
  if (doc.entries.length === 0) return { entries: [], root: null }
  if (skillsHome === null) {
    throw fail('快照里记录了技能安装，rollback 需要 skillsHome 才能安全回滚', 'INVALID_INPUT')
  }
  let root
  try {
    root = await resolveSkillsRoot(skillsHome, { create: false })
  } catch (error) {
    throw fail('技能根不可用，无法安全回滚技能部分：' + describeError(error), 'ROLLBACK_RESTORE_FAILED', error)
  }
  const flags = new Map()
  const entries = []
  for (const [index, value] of doc.entries.entries()) {
    if (
      !isPlainObject(value) ||
      typeof value.name !== 'string' ||
      !value.name.startsWith('stow-') ||
      !isSkillPackName(value.name) ||
      typeof value.path !== 'string' ||
      value.path === '' ||
      typeof value.existedBefore !== 'boolean'
    ) {
      throw fail(
        '快照的技能回滚记账已损坏：entries[' + index + '] 必须是 stow- 开头的合法技能名与 {path, existedBefore}',
        'LEDGER_CORRUPT',
      )
    }
    const target = resolve(value.path)
    if (!insideRoot(root, target)) {
      throw fail('技能回滚记账里的路径不在 skillsHome 内，拒绝删除：' + JSON.stringify(value.path), 'LEDGER_UNSAFE_PATH')
    }
    // The recorded path must be <skillsRoot>/<name>/SKILL.md, so a tampered
    // ledger cannot point this skill's backup at another file.
    if (basename(dirname(target)) !== value.name || basename(target) !== SKILL_FILE) {
      throw fail('技能回滚记账里的路径与技能名不一致：' + JSON.stringify(value.path), 'LEDGER_CORRUPT')
    }
    if (flags.has(target)) {
      if (flags.get(target) !== value.existedBefore) {
        throw fail('快照的技能回滚记账前后矛盾：' + JSON.stringify(value.path), 'LEDGER_CORRUPT')
      }
      continue
    }
    flags.set(target, value.existedBefore)
    entries.push({ name: value.name, path: target, existedBefore: value.existedBefore })
  }
  return { entries, root }
}

/**
 * Pre-check every skill entry before the first rollback write: a missing backup
 * or a recorded path that exists but is not a regular file refuses the whole
 * rollback instead of restoring half of the skills.
 * @param {{ home: string, snapshotId: string, entries: object[] }} input
 */
async function precheckSkillEntries({ home, snapshotId, entries }) {
  for (const entry of entries) {
    if (entry.existedBefore) {
      let info
      try {
        info = await lstat(skillBackupFileFor(home, snapshotId, entry.name))
      } catch (error) {
        if (error?.code === 'ENOENT') {
          throw fail('快照里的旧技能备份缺失，无法安全回滚：' + entry.path, 'ROLLBACK_BACKUP_MISSING')
        }
        throw fail('检查旧技能备份失败：' + entry.path + '：' + describeError(error), 'ROLLBACK_RESTORE_FAILED', error)
      }
      if (!info.isFile()) throw fail('快照里的旧技能备份不是普通文件：' + entry.path, 'ROLLBACK_BACKUP_MISSING')
      continue
    }
    let info
    try {
      info = await lstat(entry.path)
    } catch (error) {
      if (error?.code === 'ENOENT') continue
      throw fail('检查技能文件失败：' + entry.path + '：' + describeError(error), 'ROLLBACK_RESTORE_FAILED', error)
    }
    if (!info.isFile()) throw fail('技能台账记录的不是普通文件，拒绝回滚以免半删：' + entry.path, 'LEDGER_UNSAFE_PATH')
  }
}

/**
 * Restore pre-existing skills from their backup, delete the skills this apply
 * created (a missing one is skipped) and remove the now-empty skill directory.
 * @param {{ home: string, snapshotId: string, entries: object[] }} input
 */
async function restoreSkillEntries({ home, snapshotId, entries }) {
  for (const entry of entries) {
    try {
      if (entry.existedBefore) {
        const previous = await readFile(skillBackupFileFor(home, snapshotId, entry.name))
        await writeAtomic(entry.path, previous)
      } else {
        await rm(entry.path, { force: true })
        await removeEmptyDir(dirname(entry.path))
      }
    } catch (error) {
      throw fail('恢复或删除技能失败：' + entry.path + '：' + describeError(error), 'ROLLBACK_RESTORE_FAILED', error)
    }
  }
}

/**
 * Undo one apply: put overwritten pack files back from their snapshot backup,
 * delete the packs the apply created, then restore the state snapshot.
 * Idempotent by construction: a missing created file is skipped, re-restoring a
 * backup writes the same bytes, and store.restore does not rewrite matching
 * state — so rolling the same snapshot back twice succeeds and changes nothing.
 *
 * Error codes are split for the route layer (F7): a missing snapshot or an
 * invalid id is ROLLBACK_FAILED (404), while a snapshot that exists but cannot
 * be restored (missing backup, I/O) is ROLLBACK_RESTORE_FAILED (500).
 *
 * @param {{ snapshotId?: unknown, store?: unknown, home?: unknown, skillsHome?: unknown }} input
 *   skillsHome must be the same root the apply used when the snapshot carries a
 *   NON-EMPTY skills-created.json ledger; without it such a snapshot is refused
 *   instead of silently leaving installed skills behind. A missing or empty
 *   ledger (pre-S2 snapshot) never requires or checks the skills root.
 * @returns {Promise<{ restored: true }>}
 * @throws {ApplyError} invalid/missing snapshot, corrupt/unsafe ledger, restore failure
 */
export async function rollback(input) {
  const source = isPlainObject(input) ? input : {}
  const store = requireStore(source.store)
  const home = requireHome(source.home)
  const skillsRoot = optionalSkillsHome(source.skillsHome)
  const { snapshotId } = source
  if (typeof snapshotId !== 'string' || !SNAPSHOT_ID.test(snapshotId)) {
    throw fail('无效的快照 id：' + JSON.stringify(snapshotId), 'ROLLBACK_FAILED')
  }
  const snapshotDir = join(home, SNAPSHOTS_DIR, snapshotId)
  // A missing snapshot is a request-level 404; a present-but-unrestorable one is
  // an integrity/I/O failure (500). meta.json presence is the boundary.
  let metaInfo
  try {
    metaInfo = await lstat(join(snapshotDir, META_FILE))
  } catch (error) {
    if (error?.code === 'ENOENT') throw fail('快照不存在，无法回滚：' + snapshotId, 'ROLLBACK_FAILED')
    throw fail('检查快照失败：' + describeError(error), 'ROLLBACK_RESTORE_FAILED', error)
  }
  if (!metaInfo.isFile()) throw fail('快照元数据不是普通文件，无法回滚：' + snapshotId, 'ROLLBACK_RESTORE_FAILED')
  // S2: read the optional skill ledger first (a snapshot from before S2 has no
  // skills-created.json; an empty ledger needs no skillsHome), then the pack
  // ledger. Both are pre-checked before the first write so a missing
  // backup/unsafe path refuses the whole rollback. The skills root is resolved
  // only when the ledger really carries entries, so an old snapshot can never
  // fail because $DSH_HOME/skills is missing or unusable.
  const skillsState = await readSkillsLedger(snapshotDir, skillsRoot)
  const skillEntries = skillsState.entries
  const entries = await readLedger(snapshotDir, home)
  // Pre-check everything before the first write: a missing backup, or a path
  // that exists and is not a regular file, refuses the whole rollback instead
  // of restoring half of the packs.
  for (const entry of entries) {
    if (entry.existedBefore) {
      let backupInfo
      try {
        backupInfo = await lstat(backupFileFor(home, snapshotId, entry.path))
      } catch (error) {
        if (error?.code === 'ENOENT') {
          throw fail('快照里的旧包备份缺失，无法安全回滚：' + entry.path, 'ROLLBACK_BACKUP_MISSING')
        }
        throw fail('检查旧包备份失败：' + entry.path + '：' + describeError(error), 'ROLLBACK_RESTORE_FAILED', error)
      }
      if (!backupInfo.isFile()) {
        throw fail('快照里的旧包备份不是普通文件：' + entry.path, 'ROLLBACK_BACKUP_MISSING')
      }
      continue
    }
    let info
    try {
      info = await lstat(entry.path)
    } catch (error) {
      if (error?.code === 'ENOENT') continue
      throw fail('检查能力包文件失败：' + entry.path + '：' + describeError(error), 'ROLLBACK_RESTORE_FAILED', error)
    }
    if (!info.isFile()) {
      throw fail('台账记录的不是普通文件，拒绝回滚以免半删：' + entry.path, 'LEDGER_UNSAFE_PATH')
    }
  }
  await precheckSkillEntries({ home, snapshotId, entries: skillEntries })
  // S2 contract order: restore the skills first, then the pack files, then state.
  await restoreSkillEntries({ home, snapshotId, entries: skillEntries })
  for (const entry of entries) {
    try {
      if (entry.existedBefore) {
        const previous = await readFile(backupFileFor(home, snapshotId, entry.path))
        await writeAtomic(entry.path, previous)
      } else {
        await rm(entry.path, { force: true })
      }
    } catch (error) {
      throw fail('恢复或删除能力包失败：' + entry.path + '：' + describeError(error), 'ROLLBACK_RESTORE_FAILED', error)
    }
  }
  try {
    await store.restore(snapshotId)
  } catch (error) {
    throw fail('回滚失败：' + describeError(error), 'ROLLBACK_RESTORE_FAILED', error)
  }
  return { restored: true }
}
